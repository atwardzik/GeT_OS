void test_simple_elf_exec(void) {
        // Given
        const int fd = open("/test.elf", O_CREAT | O_RDWR, 0);
        if (fd < 0) {
                FAIL;
                return;
        }

        write(fd, elf_exec, 1644);
        lseek(fd, 0, SEEK_SET);

        // When
        char *const argv[3] = {"test.elf", nullptr};
        const pid_t elf_pid = spawn(fd, nullptr, nullptr, argv, nullptr);

        // Then
        int code;
        const pid_t returned_pid = wait(&code);
        if (returned_pid == elf_pid) {
                ASSERT_EQ(code, 0xde);
        }
        else {
                FAIL;
        }

        close(fd);
        unlink("/test.elf");
}
