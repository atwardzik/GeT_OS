#include "tests.h"

static int proc(int argc, char *argv[]) {
        if (argc == 2) {
                return 2 * strtoul(argv[1], nullptr, 10);
        }

        return 0;
}

void test_proc_exec_wait(void) {
        const pid_t pid = spawnp((void (*)(void)) proc, nullptr, nullptr, nullptr, nullptr);

        int code;
        const pid_t returned_pid = wait(&code);

        ASSERT_EQ(pid, returned_pid);
}

void test_proc_multiple_wait(void) {
        spawnp((void (*)(void)) proc, nullptr, nullptr, nullptr, nullptr);
        spawnp((void (*)(void)) proc, nullptr, nullptr, nullptr, nullptr);
        spawnp((void (*)(void)) proc, nullptr, nullptr, nullptr, nullptr);

        int code;
        wait(&code);
        wait(&code);
        wait(&code);

        PASS;
}

void test_proc_exec_return(void) {
        char *const argv[3] = {"proc", "10", nullptr};
        spawnp((void (*)(void)) proc, nullptr, nullptr, argv, nullptr);

        int code;
        wait(&code);

        ASSERT_EQ(code, 20);
}

